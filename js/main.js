const prefersFinePointer = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

if (heroEl && prefersFinePointer && !prefersReducedMotion) {
    heroEl.addEventListener('mousemove', function(event) {
        const rect = heroEl.getBoundingClientRect();
        const x = ((event.clientX - rect.left) / rect.width) * 100;
        const y = ((event.clientY - rect.top) / rect.height) * 100;
        heroEl.style.setProperty('--mx', x + '%');
        heroEl.style.setProperty('--my', y + '%');
        heroEl.classList.add('glow-active');
    });
    heroEl.addEventListener('mouseleave', function() {
        heroEl.classList.remove('glow-active');
    });
}

if (prefersFinePointer && !prefersReducedMotion) {
    document.querySelectorAll('.btn-primary, .btn-ghost').forEach(function(btn) {
        btn.addEventListener('mousemove', function(event) {
            const rect = btn.getBoundingClientRect();
            const x = event.clientX - rect.left - rect.width / 2;
            const y = event.clientY - rect.top - rect.height / 2;
            btn.style.transform = 'translate(' + (x * 0.12) + 'px,' + (y * 0.28) + 'px)';
        });
        btn.addEventListener('mouseleave', function() {
            btn.style.transform = '';
        });
    });
}

const GA_MEASUREMENT_ID = 'G-XXXXXXXXXX';

function initAnalytics() {
    if (GA_MEASUREMENT_ID.indexOf('XXXX') !== -1) {
        return;
    }
    const script = document.createElement('script');
    script.async = true;
    script.src = 'https://www.googletagmanager.com/gtag/js?id=' + GA_MEASUREMENT_ID;
    document.head.appendChild(script);
    window.dataLayer = window.dataLayer || [];
    function gtag() {
        window.dataLayer.push(arguments);
    }
    window.gtag = gtag;
    gtag('js', new Date());
    gtag('config', GA_MEASUREMENT_ID);
}

