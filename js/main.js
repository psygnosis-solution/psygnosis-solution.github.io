function renderPortfolio(lang) {
    const grid = document.getElementById('portfolioGrid');
    if (!grid) {
        return;
    }
    const data = translations[lang];
    let html = '';
    PORTFOLIO.forEach(function(project) {
        const tagsHtml = project.tags.map(function(tag) {
            return '<span class="ptag">' + tag + '</span>';
        }).join('');
        const liveBadge = project.live ? '<span class="ptag ptag-live"><span class="live-dot"></span>Live</span>' : '';
        html += ''
            + '<div class="portfolio-card reveal">'
            +   '<a href="' + project.link + '" target="_blank" rel="noopener" class="portfolio-img-wrap">'
            +     '<img src="' + project.image + '" width="800" height="500" loading="lazy" decoding="async" alt="' + project.name + '">'
            +     '<div class="portfolio-overlay"><span>' + data['portfolio-view'] + '</span></div>'
            +   '</a>'
            +   '<div class="portfolio-body">'
            +     '<div class="portfolio-eyebrow">' + (lang === 'id' ? 'Studi Kasus' : 'Case Study') + '</div>'
            +     '<div class="portfolio-tags">' + liveBadge + tagsHtml + '</div>'
            +     '<h3>' + project.name + '</h3>'
            +     '<p>' + data[project.descKey] + '</p>'
            +     '<a href="' + project.link + '" target="_blank" rel="noopener" class="portfolio-link">' + data['portfolio-link'] + '</a>'
            +   '</div>'
            + '</div>';
    });
    html += ''
        + '<div class="portfolio-card portfolio-card--placeholder reveal">'
        +   '<div class="portfolio-placeholder-inner">'
        +     '<h3>' + data['portfolio-soon-title'] + '</h3>'
        +     '<p>' + data['portfolio-soon-desc'] + '</p>'
        +   '</div>'
        + '</div>';
    grid.innerHTML = html;
    if ('IntersectionObserver' in window) {
        grid.querySelectorAll('.reveal').forEach(function(el) {
            observeReveal(el);
        });
    }
}

